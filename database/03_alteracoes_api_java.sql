-- 2. TB_ACESSO_PAINEL — contas de login do painel web
-- TB_USUARIO é o usuário final do app; quem entra no painel é o administrador
-- da Loyalty (ADMIN) ou alguém da empresa cliente (EMPRESA)
-- =====================================================================
BEGIN
  EXECUTE IMMEDIATE 'DROP TABLE TB_ACESSO_PAINEL CASCADE CONSTRAINTS';
EXCEPTION
  WHEN OTHERS THEN
    IF SQLCODE != -942 THEN -- ORA-00942: a tabela ainda não existe
      RAISE;
    END IF;
END;
/

CREATE TABLE TB_ACESSO_PAINEL
    (
     id_acesso             INTEGER GENERATED BY DEFAULT ON NULL AS IDENTITY,
     nome_acesso           VARCHAR2(100) NOT NULL,
     email_acesso          VARCHAR2(100) NOT NULL,
     senha_hash_acesso     VARCHAR2(100) NOT NULL,   -- hash BCrypt, nunca a senha em texto puro
     perfil_acesso         VARCHAR2(20)  NOT NULL,
     TB_EMPRESA_id_empresa INTEGER,                  -- NULL para o perfil ADMIN

     CONSTRAINT TB_ACESSO_PAINEL_PK        PRIMARY KEY (id_acesso),
     CONSTRAINT TB_ACESSO_PAINEL_EMAIL_UK  UNIQUE (email_acesso),
     CONSTRAINT TB_ACESSO_PAINEL_PERFIL_CK CHECK (perfil_acesso IN ('ADMIN', 'EMPRESA')),
     CONSTRAINT TB_ACESSO_PAINEL_EMP_CK    CHECK ((perfil_acesso = 'ADMIN'   AND TB_EMPRESA_id_empresa IS NULL)
                                               OR (perfil_acesso = 'EMPRESA' AND TB_EMPRESA_id_empresa IS NOT NULL)),
     CONSTRAINT TB_ACESSO_PAINEL_EMP_FK    FOREIGN KEY (TB_EMPRESA_id_empresa) REFERENCES TB_EMPRESA (id_empresa)
    );

